import type { CorosStatus, CorosStatusDto, DateRange } from '@/features/integrations/types'

import { apiFetch } from '@/services/http'

/**
 * Starts the COROS OAuth flow and returns the URL the browser must open.
 *
 * @returns The COROS authorization URL.
 * @throws {HttpError} When the backend cannot start the flow.
 */
export async function startCorosAuthorization(): Promise<string> {
  const dto = await apiFetch<{ authorization_url: string }>('/coros/authorize', {
    method: 'POST',
  })
  const url = new URL(dto.authorization_url)
  if (url.protocol !== 'https:' || !url.hostname.endsWith('.coros.com')) {
    throw new Error('COROS returned an invalid authorization URL')
  }
  return url.toString()
}

/**
 * Completes the COROS link by exchanging the OAuth callback parameters.
 *
 * @param code - Authorization code returned by COROS.
 * @param state - State generated by the backend and echoed by COROS.
 * @throws {HttpError} When the exchange fails.
 */
export async function completeCorosLink(code: string, state: string): Promise<void> {
  await apiFetch('/coros/link', {
    method: 'PUT',
    body: JSON.stringify({ code, state }),
    responseType: 'void',
  })
}

/**
 * Reads the COROS connection and last-sync status.
 *
 * @param signal - Optional abort signal.
 * @returns The normalized status model.
 * @throws {HttpError} When the request fails.
 */
export async function fetchCorosStatus(signal?: AbortSignal): Promise<CorosStatus> {
  const dto: CorosStatusDto = await apiFetch<CorosStatusDto>('/coros/status', { signal })
  return {
    linked: dto.linked,
    lastSyncAt: dto.last_sync_at ?? null,
    lastSyncStatus: dto.last_sync_status ?? 'never',
    lastSyncError: dto.last_sync_error ?? null,
    lastSyncActivityCount: dto.last_sync_activity_count ?? 0,
  }
}

/**
 * Queues a COROS activity sync.
 *
 * @param range - Optional explicit date range; the last seven days otherwise.
 * @throws {HttpError} When the sync cannot be queued.
 */
export async function syncCoros(range?: DateRange): Promise<void> {
  const query = range
    ? `?start_date=${encodeURIComponent(range.startDate)}&end_date=${encodeURIComponent(range.endDate)}`
    : ''
  await apiFetch(`/coros/sync${query}`, { method: 'POST', responseType: 'void' })
}

/**
 * Disconnects the COROS account.
 *
 * @throws {HttpError} When the request fails.
 */
export async function unlinkCoros(): Promise<void> {
  await apiFetch('/coros/unlink', { method: 'DELETE', responseType: 'void' })
}
