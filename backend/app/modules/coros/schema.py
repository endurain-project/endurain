"""COROS integration API schemas."""

from datetime import datetime

from pydantic import BaseModel, Field, StrictStr

from modules.coros.constants import SyncErrorCode, SyncStatus


class CorosStatusRead(BaseModel):
    """Connection and last-sync state shown in the settings card.

    Attributes:
        linked: Whether COROS tokens are stored for the caller.
        last_sync_at: Time of the most recent sync attempt, or None.
        last_sync_status: ``never``, ``success`` or ``error``.
        last_sync_error: Sanitized failure code, or None.
        last_sync_activity_count: Activities stored by the last successful sync.
    """

    linked: bool
    last_sync_at: datetime | None = None
    last_sync_status: SyncStatus = SyncStatus.NEVER
    last_sync_error: SyncErrorCode | None = None
    last_sync_activity_count: int = 0


class CorosAuthorizeRead(BaseModel):
    """Authorization URL the browser must open.

    Attributes:
        authorization_url: COROS OAuth authorization URL.
    """

    authorization_url: StrictStr


class CorosLinkRequest(BaseModel):
    """Callback payload returned by the COROS authorization page.

    Attributes:
        code: One-time authorization code.
        state: State generated by :func:`modules.coros.service.begin_authorization`.
    """

    code: StrictStr = Field(min_length=1, max_length=4096)
    state: StrictStr = Field(min_length=1, max_length=128)
